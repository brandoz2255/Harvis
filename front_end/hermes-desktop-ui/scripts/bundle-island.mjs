#!/usr/bin/env node
// bundle-island.mjs — bundles src/island/main.js (and the engine it imports)
// into one classic script, public/island/island.js.
//
// The island runs in an iframe sandboxed with allow-scripts only, so its origin
// is opaque. A module import from there is a CORS request with `Origin: null`,
// which nginx, the vite dev server and the Electron file loader would each need
// a header for. A plain <script src> needs none, so the page ships one bundle.
//
// The bundle is committed; src/mods/island-assets.test.ts fails when it is stale.
// Re-run after editing src/island/: node scripts/bundle-island.mjs
import { buildSync } from 'esbuild'
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const ISLAND_OUT = resolve(root, 'public', 'island', 'island.js')

export function islandBundle() {
  const result = buildSync({
    entryPoints: [resolve(root, 'src', 'island', 'main.js')],
    bundle: true,
    format: 'iife',
    target: 'es2020',
    charset: 'utf8',
    legalComments: 'none',
    banner: { js: '// Generated by scripts/bundle-island.mjs from src/island/. Do not edit.' },
    write: false
  })

  return result.outputFiles[0].text
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(ISLAND_OUT, islandBundle())
  console.log(`wrote ${ISLAND_OUT}`)
}
